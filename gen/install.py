#!/usr/bin/env python3
"""site/install.sh: the one-line installer, from the engine this site pins.

    curl -fsSL https://wherefore.sh | sh

wherefore.sh redirects to wherefore.build/install.sh, and this writes that file.
Everything it says about the product is the pinned release's own, read from its
installed metadata, never typed here: the package's name (wherefore-build -
`wherefore` on PyPI is another project's), the command it installs, the oldest
Python it runs on, and the words for the two commands it suggests next. Move the
pin and the installer moves with it, or the gate names the file that did not.

What the script does, in order: uv if it is there (`uv tool install`), else pipx,
else the newest Python's own pip into the user's site - after checking that
Python is new enough. Then it runs the command to show the version, or says the
command is not on PATH yet, and names the next two steps. It installs nothing
else and changes no shell profile.

checks/install_script.py runs it against stand-ins for uv, pipx and Python, so
each path is exercised without a network.

Run from gen/, as wherefore.json says.
"""
import importlib.metadata
import json
import pathlib
import re
import shlex
from importlib.resources import files

ROOT = pathlib.Path(__file__).resolve().parents[1]
SITE = ROOT / "site"
DIST = "wherefore-build"


def engine():
    """(package, command, oldest Python as (major, minor), {usage: does}) of the pinned release."""
    try:
        dist = importlib.metadata.distribution(DIST)
    except importlib.metadata.PackageNotFoundError:
        raise SystemExit(f"{DIST} is not installed: install the release requirements-engine.txt pins")
    name = dist.metadata["Name"]
    scripts = [ep.name for ep in dist.entry_points if ep.group == "console_scripts"]
    if len(scripts) != 1:
        raise SystemExit(f"{name} installs {len(scripts)} commands ({', '.join(scripts)}); "
                         f"the installer names exactly one")
    need = re.fullmatch(r">=\s*(\d+)\.(\d+)", dist.metadata.get("Requires-Python", "").strip())
    if not need:
        raise SystemExit(f"{name} says Requires-Python {dist.metadata.get('Requires-Python')!r}, "
                         f"which the installer cannot check: it reads `>=X.Y` only")
    rows = json.loads((files("wherefore") / "commands.json").read_text(encoding="utf-8"))["commands"]
    does = {c["usage"].split()[1]: c["does"] for c in rows}
    return name, scripts[0], (int(need[1]), int(need[2])), does


def script(name, command, need, does):
    q = shlex.quote
    major, minor = need
    for word in ("scan", "init"):
        if word not in does:
            raise SystemExit(f"the installer suggests `{command} {word}`, which the pinned release does not have")
    return f"""#!/bin/sh
# Installs Wherefore:  curl -fsSL https://wherefore.sh | sh
#
# Generated by gen/install.py from the release wherefore.build pins. Read it
# before you run it: it installs one package, {name}, with uv, pipx or
# pip - whichever you have - and changes nothing else.
set -eu

PACKAGE={q(name)}
COMMAND={q(command)}

say() {{ printf '%s\\n' "$*"; }}
fail() {{ printf 'wherefore install: %s\\n' "$*" >&2; exit 1; }}

if command -v uv >/dev/null 2>&1; then
  say "Installing $PACKAGE with uv"
  uv tool install --upgrade "$PACKAGE"
elif command -v pipx >/dev/null 2>&1; then
  say "Installing $PACKAGE with pipx"
  pipx install --force "$PACKAGE"
else
  PY=
  for candidate in python3 python; do
    if command -v "$candidate" >/dev/null 2>&1; then PY=$candidate; break; fi
  done
  [ -n "$PY" ] || fail "no Python here. Install uv (https://docs.astral.sh/uv/) or Python {major}.{minor} or later, then run this again."
  "$PY" -c 'import sys; sys.exit(0 if sys.version_info >= ({major}, {minor}) else 1)' \\
    || fail "$PACKAGE needs Python {major}.{minor} or later, and $("$PY" -V 2>&1) is what is here. Installing uv is the quickest way past it."
  say "Installing $PACKAGE with $PY -m pip, for this user"
  "$PY" -m pip install --user --upgrade "$PACKAGE" \\
    || fail "pip could not install $PACKAGE here. Install uv (https://docs.astral.sh/uv/) and run this again."
fi

say ""
if command -v "$COMMAND" >/dev/null 2>&1; then
  "$COMMAND" --version
else
  say "$PACKAGE is installed, but \\`$COMMAND\\` is not on your PATH yet: open a new terminal, or add the folder the installer named."
fi
say ""
say "Next:"
say {q(f"  {command} scan .    {does['scan']}")}
say {q(f"  {command} init      {does['init']}")}
"""


def main():
    SITE.mkdir(exist_ok=True)
    out = SITE / "install.sh"
    out.write_text(script(*engine()), encoding="utf-8")


if __name__ == "__main__":
    main()
