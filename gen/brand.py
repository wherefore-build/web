#!/usr/bin/env python3
"""The brand pack, from brand/tokens.json: the stylesheet, the fonts, the page.

site/brand.css carries every colour, typeface and radius as a custom property,
and the @font-face rules for the fonts it serves itself. Every page links it,
and no page or stylesheet says a colour of its own (checks/one_palette.py), so
a token changed here changes every page by being regenerated.

site/fonts/ holds the font files and their licences, copied from brand/fonts/
exactly. The site loads nothing from elsewhere (checks/self_contained.py), so
the fonts are served from it, under the SIL Open Font License each carries.

site/brand/ is the brand pack a person reads: every token with its role and its
reason, every text colour against every ground it is set on with the contrast
it reaches (computed here, and held by checks/contrast.py), the type, the
shapes, the wordmark, and the fonts with their licences. A copy of the tokens
sits beside it, for whoever builds something else from them.

Run from gen/, as wherefore.json says, before site.py.
"""
import json
import shutil
from importlib.resources import files

from kit import FACTS, ROOT, SITE, TOKENS, banner, colours, contrast, esc, head

CSS_HEADER = "/* Generated by gen/brand.py from brand/tokens.json. Edit that, not this. */\n"


def stylesheet(t):
    faces = []
    for role, face in t["type"].items():
        for f in face["faces"]:
            faces.append(
                "@font-face {\n"
                f'  font-family: "{face["family"]}";\n'
                f'  font-style: {f["style"]};\n'
                f'  font-weight: {f["weight"]};\n'
                "  font-display: swap;\n"
                f'  src: url("fonts/{f["file"]}") format("woff2");\n'
                "}\n")
    props = [f"  --{name}: var(--{c['same_as']});" if "same_as" in c else f"  --{name}: {c['value']};"
             for name, c in t["color"].items()]
    props += [f'  --font-{role}: "{face["family"]}", {face["fallback"]};'
              for role, face in t["type"].items()]
    props += [f"  --radius-{name}: {r['value']};" for name, r in t["radius"].items()]
    return CSS_HEADER + "".join(faces) + ":root {\n" + "\n".join(props) + "\n}\n"


def fonts(t):
    """Copy every face and licence the tokens name, and nothing else."""
    out = SITE / "fonts"
    if out.exists():
        shutil.rmtree(out)
    for face in t["type"].values():
        for rel in [f["file"] for f in face["faces"]] + [face["licence"]]:
            src = ROOT / "brand/fonts" / rel
            if not src.is_file():
                raise SystemExit(f"brand/tokens.json names brand/fonts/{rel}, which is not there")
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, out / rel)


def gate_usage():
    """The gate as the engine this site pins writes it, for the mono sample."""
    rows = json.loads((files("wherefore") / "commands.json").read_text(encoding="utf-8"))["commands"]
    return next(c["usage"] for c in rows if c["usage"].split()[1:2] == ["gate"])


def page(t):
    name = FACTS["company"]["name"]
    value = colours(t)
    swatches = "\n".join(
        f'<li class="swatch"><div class="swatch-chip" style="background: var(--{esc(k)})"></div>'
        f'<div class="swatch-text"><p class="swatch-name">{esc(k)} <code>'
        + (f'same as {esc(c["same_as"])}' if "same_as" in c else esc(c["value"]))
        + f'</code></p><p class="swatch-role">{esc(c["role"])}</p><p class="why">{esc(c["why"])}</p></div></li>'
        for k, c in t["color"].items())
    pairs = "\n".join(
        f'<tr><td><code>{esc(p["text"])}</code></td><td><code>{esc(p["on"])}</code></td>'
        f'<td class="sample-cell" style="color: var(--{esc(p["text"])}); background: var(--{esc(p["on"])})">Aa {esc(name)}</td>'
        f'<td class="num">{contrast(value[p["text"]], value[p["on"]]):.1f}:1</td>'
        f'<td class="num">{p["min"]:g}:1</td></tr>'
        for p in t["contrast"]["pairs"])
    samples = {"display": f'{FACTS["hero"]["headline"]} {FACTS["hero"]["headline_end"]}', "body": FACTS["hero"]["lede"],
               "mono": "$ " + gate_usage()}
    specimens = "\n".join(
        f'<div class="specimen"><p class="label">{esc(role)} · {esc(face["family"])} · '
        f'{esc(", ".join(str(f["weight"]) + (" italic" if f["style"] == "italic" else "") for f in face["faces"]))}</p>'
        f'<p class="sample sample-{esc(role)}">{esc(samples[role])}</p>'
        f'<p class="swatch-role">{esc(face["role"])}</p><p class="why">{esc(face["why"])}</p></div>'
        for role, face in t["type"].items())
    shapes = "\n".join(
        f'<li class="shape-item"><div class="shape" style="border-radius: var(--radius-{esc(k)})"></div>'
        f'<p class="swatch-name">{esc(k)} <code>{esc(r["value"])}</code></p>'
        f'<p class="swatch-role">{esc(r["role"])}</p><p class="why">{esc(r["why"])}</p></li>'
        for k, r in t["radius"].items())
    licences = "\n".join(
        f'<tr><td>{esc(face["family"])}</td><td>{esc(role)}</td><td><code>{esc(face["source"])}</code></td>'
        f'<td><a href="../fonts/{esc(face["licence"])}">SIL Open Font License 1.1</a></td></tr>'
        for role, face in t["type"].items())
    return f"""<!doctype html>
<html lang="en">
<head>
{head(name + " — brand", "The brand, said once: every colour, typeface and shape, with its reason.", "../brand.css")}
<link rel="stylesheet" href="../page.css">
</head>
<body>
{banner()}<header class="top"><div class="wrap"><a class="name" href="../">{esc(name)}</a>
<nav aria-label="On this page"><a href="#colour">Colour</a><a href="#type">Type</a><a href="#shape">Shape</a><a href="#fonts">Fonts</a></nav></div></header>
<main id="top">
<section class="hero"><div class="wrap">
<p class="eyebrow">Brand · {esc(t["status"])}</p>
<h1 class="wordmark">{esc(name)}</h1>
<p class="lede">The brand, said once. Every page, card and slide takes its colours, type and shapes from one file, and this page is built from it too.</p>
<p class="why">{esc(t["idea"])}</p>
<p class="files"><a href="tokens.json">tokens.json</a> <a href="../brand.css">brand.css</a></p>
</div></section>
<section id="colour"><div class="wrap">
<h2>Colour</h2>
<ul class="swatches">
{swatches}
</ul>
<h3>Every text colour, on every ground it is set on</h3>
<div class="table-box"><table class="pairs">
<thead><tr><th scope="col">Text</th><th scope="col">On</th><th scope="col">Sample</th><th scope="col">Contrast</th><th scope="col">At least</th></tr></thead>
<tbody>
{pairs}
</tbody>
</table></div>
</div></section>
<section id="type"><div class="wrap">
<h2>Type</h2>
{specimens}
</div></section>
<section id="shape"><div class="wrap">
<h2>Shape</h2>
<ul class="shapes">
{shapes}
</ul>
<h3>Wordmark</h3>
<div class="wordmarks"><p class="wordmark wordmark-ground">{esc(name)}</p><p class="wordmark wordmark-accent">{esc(name)}</p></div>
<p class="why">{esc(t["wordmark"]["why"])}</p>
</div></section>
<section id="fonts"><div class="wrap">
<h2>Fonts and licences</h2>
<div class="table-box"><table class="pairs">
<thead><tr><th scope="col">Family</th><th scope="col">Role</th><th scope="col">From</th><th scope="col">Licence</th></tr></thead>
<tbody>
{licences}
</tbody>
</table></div>
</div></section>
</main>
<footer><div class="wrap"><p>Generated from brand/tokens.json. <a href="../">Back to {esc(name)}</a></p></div></footer>
</body>
</html>
"""


def main():
    t = TOKENS
    SITE.mkdir(exist_ok=True)
    (SITE / "brand.css").write_text(stylesheet(t), encoding="utf-8")
    fonts(t)
    (SITE / "brand").mkdir(exist_ok=True)
    shutil.copyfile(ROOT / "brand/tokens.json", SITE / "brand/tokens.json")
    (SITE / "brand/index.html").write_text(page(t), encoding="utf-8")


if __name__ == "__main__":
    main()
